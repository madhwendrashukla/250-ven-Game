/** Palette tones. The first group is the truck-art palette; the second are semantic aliases. */
export type Tone =
  | 'marigold'
  | 'rani'
  | 'teal'
  | 'parrot'
  | 'coral'
  | 'chili'
  | 'ink'
  | 'paper'
  | 'accent'
  | 'good'
  | 'bad'
  | 'warn'
  | 'info'
  | 'neutral'
  | 'violet';

export function Icon({ name, size = 18, ...props }: { name: string } & LucideProps) {
  const C = ICONS[name] ?? CircleHelp;
  return <C size={size} strokeWidth={2.4} aria-hidden {...props} />;
}

/** An icon on a soft coloured tile — used for ideas, segments, events and archetypes. */
export function IconBadge({
  name,
  tone = 'accent',
  size = 'md',
  className = '',
}: {
  name: string;
  tone?: Tone;
  size?: 'sm' | 'md' | 'lg' | 'xl';
  className?: string;
}) {
  const px = { sm: 14, md: 18, lg: 26, xl: 40 }[size];
  return (
    <span className={`icon-badge icon-badge-${size} tone-${tone} ${className}`}>
      <Icon name={name} size={px} />
    </span>
  );
}

